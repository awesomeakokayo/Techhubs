/**
 * TechSkillHub — External resource content verifier (authoritative link evidence).
 *
 * Resolves every learning resource the catalogue maps to a stage (through the
 * same `lib/stage-resources.ts` resolver the served path and the audit use) and
 * fetches each unique URL to record REAL evidence. Extraction lives in
 * `scripts/lib/content-extract.mjs`.
 *
 * Evidence levels (see `lib/resource-verification.ts`):
 *   1 URL discovered · 2 destination + identity verified · 3 actual content inspected
 *   4 playback/interaction verified
 *
 * Honest limits: extracts and stores a concise original excerpt from a page the
 * publisher serves publicly. It does not play videos, log in, or bypass any
 * access control, and never reproduces the material. Video and interactive
 * resources therefore cannot reach level 4 here and are reported as a visible
 * limitation.
 *
 * Usage:
 *   node scripts/verify-resource-links.mjs            # refresh probe data
 *   node scripts/verify-resource-links.mjs --check    # exit 1 if a resource cannot be resolved
 */

import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadTsModule } from './lib/load-ts.mjs'
import { probeUrl, MIN_CONTENT_CHARS } from './lib/content-extract.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'scripts', 'resource-probe.json')
const checkedAt = new Date().toISOString().slice(0, 10)

const { TRACKS } = await loadTsModule(join(root, 'lib', 'tracks.ts'))
const { resolveStageResources, normalizeUrl } = await loadTsModule(join(root, 'lib', 'stage-resources.ts'))

// ── Enumerate the resource map straight from the catalogue ──────────────────
const byUrl = new Map()
for (const track of TRACKS) {
  for (const stage of track.roadmap) {
    for (const entry of resolveStageResources(track.id, stage.id)) {
      const key = normalizeUrl(entry.resource.url)
      if (!byUrl.has(key)) byUrl.set(key, { url: entry.resource.url, resourceIds: new Set(), trackStages: new Set() })
      const record = byUrl.get(key)
      record.resourceIds.add(entry.resource.id)
      record.trackStages.add(`${track.id}:${stage.id}`)
    }
  }
}
const urls = [...byUrl.values()].sort((a, b) => a.url.localeCompare(b.url))
console.log(`Resolved ${urls.length} unique resource URLs across ${TRACKS.length} tracks.`)

async function mapLimit(items, limit, worker) {
  const results = new Array(items.length)
  let cursor = 0
  const runners = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor++
      results[index] = await worker(items[index], index)
    }
  })
  await Promise.all(runners)
  return results
}

const probes = await mapLimit(urls, 6, async (entry) => [normalizeUrl(entry.url), await probeUrl(entry.url, checkedAt)])
const entries = Object.fromEntries(probes)

// Paced retry for anything the first pass could not read (rate limits / transient).
const retriable = urls.filter((entry) => {
  const value = entries[normalizeUrl(entry.url)]
  return !value || value.status === 0 || value.status === 429 || value.status >= 500
})
if (retriable.length) {
  console.log(`Retrying ${retriable.length} URLs slowly…`)
  for (const entry of retriable) {
    await new Promise((resolve) => setTimeout(resolve, 1200))
    const result = await probeUrl(entry.url, checkedAt)
    const key = normalizeUrl(entry.url)
    const previous = entries[key]
    if (result.status >= 200 && result.status < 400) entries[key] = result
    else if (!(previous && previous.status) && result.status) entries[key] = result
    else if (previous && previous.status && !result.status) {
      /* keep the informational existing status */
    } else entries[key] = result
  }
}

const failing = []
let contentInspected = 0
for (const [key, value] of Object.entries(entries)) {
  if (!value || value.status < 200 || value.status >= 400) failing.push({ url: key, status: value?.status, error: value?.error })
  if (value && value.contentChars >= MIN_CONTENT_CHARS && !value.paywalled) contentInspected += 1
}

const payload = {
  generatedAt: checkedAt,
  schema: 2,
  note: 'Generated by scripts/verify-resource-links.mjs. Destination, identity AND extracted main-content evidence. Concise excerpts only; no material is rehosted. Playback (level 4) is never claimed here.',
  total: Object.keys(entries).length,
  reachable: Object.keys(entries).length - failing.length,
  contentInspected,
  entries,
}
writeFileSync(OUT, JSON.stringify(payload, null, 2) + '\n', 'utf8')

console.log(`Probed ${payload.total} URLs: ${payload.reachable} reachable, ${contentInspected} with inspected content.`)
if (failing.length) {
  console.log('\nUnreachable / non-2xx resources:')
  for (const item of failing.sort((a, b) => a.status - b.status)) {
    console.log(`  [${item.status}] ${item.url}${item.error ? ` — ${item.error}` : ''}`)
  }
}

if (process.argv.includes('--check')) {
  if (failing.length) {
    console.error(`\nFAIL: ${failing.length} mapped resource URLs did not resolve.`)
    process.exit(1)
  }
  console.log('\nOK: every mapped resource URL resolved.')
}

export { payload }
